"""A rendered nexyconfig.py ends with exactly one newline.

The starter configs are generated by Jinja2 templates. A whitespace-control marker
that eats the trailing newline leaves `cat nexyconfig.py` glued to the next prompt
and makes ruff report W292 in a brand-new project.
"""

from pathlib import Path

import pytest
from jinja2 import Environment, FileSystemLoader

SHARED = Path(__file__).resolve().parents[4] / "nexy" / "modules" / "cli" / "templates" / "_shared"


@pytest.mark.parametrize("starter", ["web", "api"])
@pytest.mark.parametrize("orm", [None, "sqlalchemy"])
def test_nexyconfig_template_ends_with_one_newline(starter: str, orm: str | None) -> None:
    env = Environment(loader=FileSystemLoader([str(SHARED)]))  # nosec B701
    context = {
        "client_framework": "react",
        "FBRouter": True,
        "useCSR": False,
        "orm": orm,
        "project_type": starter,
    }
    rendered = env.get_template(f"{starter}/nexyconfig.py.jinja2").render(**context)
    assert rendered.endswith("\n")
    assert not rendered.endswith("\n\n")
