"""The manifest shared by the Python markup helper and the five client adapters."""

from __future__ import annotations

import json
from pathlib import Path

from nexy.helpers.fs.path import PathUtil

IMAGE_MANIFEST = Path("__nexy__/image-manifest.json")
IMAGE_TYPESCRIPT = Path("__nexy__/src/image-manifest.auto.ts")

Variant = dict[str, str | int]


def normalize_source(value: str | Path) -> str:
    """The manifest key of a local image path, without a leading slash or `./`."""
    text = str(value).replace("\\", "/").strip()
    while text.startswith("./"):
        text = text[2:]
    text = text.lstrip("/")
    return text.removeprefix("public/")


def load_manifest(root: Path | None = None) -> dict[str, Variant]:
    """Read the build manifest, or return an empty one before the first build."""
    path = (root or Path.cwd()) / IMAGE_MANIFEST
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def write_manifest(manifest: dict[str, Variant], root: Path | None = None) -> None:
    """Write the manifest the Python helper reads at render time."""
    path = (root or Path.cwd()) / IMAGE_MANIFEST
    PathUtil.write_if_changed(path, json.dumps(manifest, indent=2, sort_keys=True) + "\n")


def render_typescript(manifest: dict[str, Variant]) -> str:
    """Render the generated module the client adapters import."""
    header = "// Generated by Nexy from the local images found in src/ and public/. Do not edit.\n"
    types = (
        "export type ImageVariant = {\n"
        "  src: string\n"
        "  srcset: string\n"
        "  sizes: string\n"
        "  width: number\n"
        "  height: number\n"
        "}\n"
    )
    body = json.dumps(manifest, indent=2, sort_keys=True)
    return f"{header}{types}\nexport const IMAGE_VARIANTS: Record<string, ImageVariant> = {body}\n"


def write_image_typescript(manifest: dict[str, Variant], root: Path | None = None) -> None:
    """Publish the manifest to the client build, before Vite bundles the adapters."""
    PathUtil.write_if_changed((root or Path.cwd()) / IMAGE_TYPESCRIPT, render_typescript(manifest))
