import importlib
import pkgutil
import sys
from pathlib import Path

from fastapi import FastAPI
from rich.markup import escape

from nexy.core.config import Config
from nexy.helpers.common.console import console
from nexy.helpers.common.pycheck import describe
from nexy.helpers.fs.path import PathUtil
from nexy.modules.routers.actions.endpoint import make_endpoint
from nexy.modules.routers.actions.spec import ActionSpec, build_spec
from nexy.modules.routers.actions.store import ACTIONS_STORE
from nexy.modules.routers.actions.typescript import Declarations, ts_type

# The router imports the route files and reports the ones that fail: not reported twice.
_ROUTES = Config.ROUTER_PATH.replace("/", ".") + "."
_RUNTIME = Path(__file__).resolve().parents[2] / "frontend" / "client" / "actions.ts"
_HEADER = "// Generated by Nexy from the @Action functions of src/. Do not edit.\n"


class ActionEngine:
    def __init__(self, output_dir: str | None = None):
        self.output_dir = output_dir
        self.ignore_folders = {
            "__pycache__",
            ".venv",
            "venv",
            "node_modules",
            ".git",
            "dist",
            "build",
        }

    def discover(self, start_dir: str = "src") -> None:
        """Import the modules of *start_dir* so their actions register; report failures."""
        base_path = Path(start_dir).resolve()
        if not base_path.exists():
            return

        root_name = base_path.name
        if str(base_path.parent) not in sys.path:
            sys.path.append(str(base_path.parent))

        for _loader, name, _is_pkg in pkgutil.walk_packages(
            [str(base_path)], prefix=f"{root_name}.", onerror=self._report
        ):
            if any(ignored in name.split(".") for ignored in self.ignore_folders):
                continue
            try:
                importlib.import_module(name)
            except Exception as error:
                if not name.startswith(_ROUTES):
                    self._report(name, error)

    @staticmethod
    def _report(name: str, error: BaseException | None = None) -> None:
        """Say which module failed to import and why; the others still load."""
        if error is None:
            error = sys.exc_info()[1]
        if error is None:
            return
        problem = describe(error)
        console.print(f"  [red]x[/red] {escape(name)}: {escape(problem.format())}")

    def specs(self) -> list[ActionSpec]:
        return [build_spec(func_id, handler) for func_id, handler in ACTIONS_STORE.registry.items()]

    def include_router(self, router: FastAPI) -> FastAPI:
        """Mounts all registered actions onto the router."""
        for spec in self.specs():
            path_hash = ACTIONS_STORE._generate_hash(spec.func_id)
            encrypted_path = f"/_nx_{path_hash}"
            ACTIONS_STORE.path_map[spec.func_id] = encrypted_path
            router.add_api_route(
                path=encrypted_path,
                endpoint=make_endpoint(spec),
                methods=["POST"],
                name=spec.name,
                tags=["All Actions"],
                response_model=None,
                openapi_extra={
                    "requestBody": {
                        "required": spec.takes_input,
                        "content": {"application/json": {"schema": spec.model.model_json_schema()}},
                    }
                },
            )
        return router

    def render_client(self) -> str:
        """The TypeScript module that exposes every action as a typed function."""
        declarations: Declarations = {}
        lines = []
        for spec in self.specs():
            url = ACTIONS_STORE.path_map.get(spec.func_id) or (
                f"/_nx_{ACTIONS_STORE._generate_hash(spec.func_id)}"
            )
            lines.append(
                f"export const {spec.name} = defineAction<{self._input(spec, declarations)}, "
                f"{ts_type(spec.returns, declarations)}>({url!r}, {spec.func_id!r})"
            )
        types = [f"export type {name} = {body}" for name, body in sorted(declarations.items())]
        head = [_HEADER, "import { defineAction } from './action-runtime.ts'", ""]
        return "\n".join([*head, *types, *([""] if types else []), *lines, ""])

    @staticmethod
    def _input(spec: ActionSpec, declarations: Declarations) -> str:
        if not spec.takes_input:
            return "void"
        return ts_type(spec.model, declarations, mode="validation", inline=True)

    def generate_client(self, directory: str | Path | None = None) -> Path | None:
        """Write `actions.ts` and its runtime for `@nexy/actions`; None without actions."""
        target = Path(directory or self.output_dir or "__nexy__/src")
        if not ACTIONS_STORE.registry:
            (target / "actions.ts").unlink(missing_ok=True)
            return None
        target.mkdir(parents=True, exist_ok=True)
        PathUtil.write_if_changed(target / "action-runtime.ts", _RUNTIME.read_text("utf-8"))
        PathUtil.write_if_changed(target / "actions.ts", self.render_client())
        return target / "actions.ts"


ACTION_ENGINE = ActionEngine(output_dir="__nexy__/src")
