"""Reject AI attribution in commit messages.

GitHub counts every ``Co-authored-by`` trailer as a contributor. An AI trailer
therefore adds a bot account to the contributor graph and misattributes work
the human owns. The same applies to the "Generated with" boilerplate that some
tools append.

Usage:
    python scripts/check_attribution.py --message-file .git/COMMIT_EDITMSG
    python scripts/check_attribution.py --range origin/main..HEAD
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

# Lower-case fragments matched against trailer values and generator lines.
AI_TOOLS: tuple[str, ...] = (
    "aider",
    "amazon q",
    "anthropic",
    "bolt.new",
    "chatgpt",
    "claude",
    "codebuff",
    "codex",
    "coderabbit",
    "copilot",
    "cursor",
    "devin",
    "deepseek",
    "freebuff",
    "gemini",
    "junie",
    "kilo code",
    "lovable",
    "mistral",
    "ollama",
    "openai",
    "openhands",
    "qodo",
    "qwen",
    "replit",
    "roo code",
    "sourcegraph",
    "sweep",
    "tabnine",
    "windsurf",
)

TRAILER_KEYS: tuple[str, ...] = (
    "co-authored-by",
    "generated-by",
    "generated-with",
    "assisted-by",
    "made-with",
)

GENERATOR_PREFIXES: tuple[str, ...] = (
    "generated with",
    "generated by",
    "created with",
    "made with",
)

_RECORD_SEPARATOR = "\x1e"
_FIELD_SEPARATOR = "\x1f"


# Mail domains that only AI vendors' tools use as a commit identity.
AI_DOMAINS: tuple[str, ...] = (
    "aider.chat",
    "anthropic.com",
    "codebuff.com",
    "cognition.ai",
    "cursor.com",
    "cursor.sh",
    "devin.ai",
    "openai.com",
    "qodo.ai",
    "sourcegraph.com",
    "windsurf.com",
)

_IDENTITY = re.compile(r"^(?P<name>.*?)\s*(?:<(?P<email>[^>]*)>)?\s*$")


def names_ai(text: str) -> bool:
    """Return True when *text* names a known AI tool as a whole word.

    Whole words only: "Ali Haider" does not name Aider.
    """
    lowered = text.lower()
    return any(
        re.search(rf"(?<![a-z0-9]){re.escape(tool)}(?![a-z0-9])", lowered) for tool in AI_TOOLS
    )


def is_ai_identity(value: str) -> bool:
    """Return True when a ``Name <email>`` trailer value is an AI tool, not a person.

    A person can share a first name with a tool ("Devin Lee <devin@corp.com>"), so the name
    alone is not enough: the identity must be a bot account, a vendor mail domain, or a
    tool name paired with a no-reply address.
    """
    match = _IDENTITY.match(value.strip())
    name = (match.group("name") if match else value).strip()
    email = ((match.group("email") if match else "") or "").strip().lower()
    domain = email.rpartition("@")[2]
    local = email.partition("@")[0]

    if "[bot]" in name.lower() or "[bot]" in local:
        return True
    if any(domain == vendor or domain.endswith("." + vendor) for vendor in AI_DOMAINS):
        return True
    if name.lower() in AI_TOOLS and domain.endswith("github.com"):
        return True  # "Copilot <...@users.noreply.github.com>": a bare tool name, not a person
    no_reply = local.startswith("noreply") or local.startswith("no-reply") or not email
    return names_ai(name) and no_reply


def offending_lines(message: str) -> list[str]:
    """Return the lines of *message* that attribute work to an AI."""
    found: list[str] = []
    for line in message.splitlines():
        stripped = line.strip().lstrip("🤖 ").strip()
        if not stripped:
            continue
        key, _, value = stripped.partition(":")
        if key.strip().lower() in TRAILER_KEYS:
            if is_ai_identity(value) or (
                key.strip().lower() != "co-authored-by" and names_ai(value)
            ):
                found.append(stripped)
        elif stripped.lower().startswith(GENERATOR_PREFIXES) and names_ai(stripped):
            found.append(stripped)
    return found


def messages_in_range(rev_range: str) -> list[tuple[str, str]]:
    """Return ``(sha, message)`` for every commit in *rev_range*."""
    result = subprocess.run(  # nosec B603/B607 - fixed argv, user-supplied revision
        ["git", "log", f"--format=%H{_FIELD_SEPARATOR}%B{_RECORD_SEPARATOR}", rev_range],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(f"git log failed: {result.stderr.strip()}")

    commits: list[tuple[str, str]] = []
    for record in result.stdout.split(_RECORD_SEPARATOR):
        if not record.strip():
            continue
        sha, _, body = record.partition(_FIELD_SEPARATOR)
        commits.append((sha.strip(), body))
    return commits


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--message-file", type=Path, help="commit message file to check")
    source.add_argument("--range", dest="rev_range", help="git revision range to check")
    args = parser.parse_args()

    if args.message_file is not None:
        message = args.message_file.read_text(encoding="utf-8", errors="replace")
        violations = offending_lines(message)
        if violations:
            print("[attribution] commit message rejected:", file=sys.stderr)
            for line in violations:
                print(f"  {line}", file=sys.stderr)
            print(
                "[attribution] remove the AI trailer; the human owns the contribution.",
                file=sys.stderr,
            )
            return 1
        return 0

    failures = 0
    for sha, message in messages_in_range(args.rev_range):
        violations = offending_lines(message)
        if violations:
            failures += 1
            subject = message.strip().splitlines()[0] if message.strip() else ""
            print(f"[attribution] {sha[:7]} {subject}", file=sys.stderr)
            for line in violations:
                print(f"  {line}", file=sys.stderr)
    if failures:
        print(
            f"[attribution] {failures} commit(s) attribute work to an AI. "
            "See CONTRIBUTING.md, section Attribution.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
