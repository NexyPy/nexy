"""Reject AI attribution in commit messages.

GitHub counts every ``Co-authored-by`` trailer as a contributor. An AI trailer
therefore adds a bot account to the contributor graph and misattributes work
the human owns. The same applies to the "Generated with" boilerplate that some
tools append.

Usage:
    python scripts/check_attribution.py --message-file .git/COMMIT_EDITMSG
    python scripts/check_attribution.py --range origin/main..HEAD
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

# Lower-case fragments matched against trailer values and generator lines.
AI_TOOLS: tuple[str, ...] = (
    "aider",
    "amazon q",
    "anthropic",
    "bolt.new",
    "chatgpt",
    "claude",
    "codebuff",
    "codex",
    "coderabbit",
    "copilot",
    "cursor",
    "devin",
    "deepseek",
    "freebuff",
    "gemini",
    "junie",
    "kilo code",
    "lovable",
    "mistral",
    "ollama",
    "openai",
    "openhands",
    "qodo",
    "qwen",
    "replit",
    "roo code",
    "sourcegraph",
    "sweep",
    "tabnine",
    "windsurf",
)

TRAILER_KEYS: tuple[str, ...] = (
    "co-authored-by",
    "generated-by",
    "generated-with",
    "assisted-by",
    "made-with",
)

GENERATOR_PREFIXES: tuple[str, ...] = (
    "generated with",
    "generated by",
    "created with",
    "made with",
)

_RECORD_SEPARATOR = "\x1e"
_FIELD_SEPARATOR = "\x1f"


def names_ai(text: str) -> bool:
    """Return True when *text* mentions a known AI tool or vendor."""
    lowered = text.lower()
    return any(tool in lowered for tool in AI_TOOLS)


def offending_lines(message: str) -> list[str]:
    """Return the lines of *message* that attribute work to an AI."""
    found: list[str] = []
    for line in message.splitlines():
        stripped = line.strip().lstrip("\U0001f916 ").strip()
        if not stripped:
            continue
        key = stripped.split(":", 1)[0].strip().lower()
        is_trailer = key in TRAILER_KEYS
        is_generator = stripped.lower().startswith(GENERATOR_PREFIXES)
        if names_ai(stripped) and (is_trailer or is_generator):
            found.append(stripped)
    return found


def messages_in_range(rev_range: str) -> list[tuple[str, str]]:
    """Return ``(sha, message)`` for every commit in *rev_range*."""
    result = subprocess.run(  # nosec B603/B607 - fixed argv, user-supplied revision
        ["git", "log", f"--format=%H{_FIELD_SEPARATOR}%B{_RECORD_SEPARATOR}", rev_range],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(f"git log failed: {result.stderr.strip()}")

    commits: list[tuple[str, str]] = []
    for record in result.stdout.split(_RECORD_SEPARATOR):
        if not record.strip():
            continue
        sha, _, body = record.partition(_FIELD_SEPARATOR)
        commits.append((sha.strip(), body))
    return commits


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--message-file", type=Path, help="commit message file to check")
    source.add_argument("--range", dest="rev_range", help="git revision range to check")
    args = parser.parse_args()

    if args.message_file is not None:
        message = args.message_file.read_text(encoding="utf-8", errors="replace")
        violations = offending_lines(message)
        if violations:
            print("[attribution] commit message rejected:", file=sys.stderr)
            for line in violations:
                print(f"  {line}", file=sys.stderr)
            print(
                "[attribution] remove the AI trailer; the human owns the contribution.",
                file=sys.stderr,
            )
            return 1
        return 0

    failures = 0
    for sha, message in messages_in_range(args.rev_range):
        violations = offending_lines(message)
        if violations:
            failures += 1
            subject = message.strip().splitlines()[0] if message.strip() else ""
            print(f"[attribution] {sha[:7]} {subject}", file=sys.stderr)
            for line in violations:
                print(f"  {line}", file=sys.stderr)
    if failures:
        print(
            f"[attribution] {failures} commit(s) attribute work to an AI. "
            "See CONTRIBUTING.md, section Attribution.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
